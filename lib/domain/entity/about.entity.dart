class AppVerEntity {
  final String appVersion;
  final String buildNumber;
  final String appId;
  final String appName;
  final String url;
  final String desc;
  final String kodeOrg;

  AppVerEntity({
    required this.appVersion,
    required this.buildNumber,
    required this.appId,
    required this.appName,
    required this.url,
    required this.desc,
    required this.kodeOrg,
  });
}
